'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const text=fs.readFileSync(path.join(__dirname,'web/app.js'),'utf8');
const source=text.split('// BEGIN WEEKLY PLAN MODEL')[1].split('// END WEEKLY PLAN MODEL')[0];
const context=vm.createContext({});vm.runInContext(source,context);
const run=(week,profile,clock)=>JSON.parse(JSON.stringify(context.planItems(week,profile,Date.parse(clock))));
const event=(id,title,start,checked=false)=>({id,title,start,checked_in:checked,end:new Date(Date.parse(start)+3600000).toISOString()});
const wish=(sport,day,from=0,to=24)=>({sport,weekdays:[day],time_from:from,time_to:to});
const monday=event('monday','Volleyball','2026-10-25T21:30:00Z');
const week={week_start:'2026-10-26',events:[monday,event('booked','Swimming','2026-10-27T10:00:00+03:00',true),event('conflict','Yoga','2026-10-27T10:30:00+03:00'),event('wait','Boxing','2026-10-28T12:00:00+03:00'),event('table','Table tennis - Beginners','2026-10-29T12:00:00+03:00'),event('cancel','Volleyball','2026-10-30T12:00:00+03:00')]};
const profile={wishlist:[wish('Volleyball',0,0,1),wish('Volleyball',0),wish('Yoga',1),wish('Tennis',3),wish('Volleyball',4)],cancelled_ids:['cancel'],waitlist:[{id:'wait',title:'Boxing',start:'2026-10-28T12:00:00+03:00'},{id:'outside',title:'Boxing',start:'2026-11-02T12:00:00+03:00'}]};
let items=run(week,profile,'2026-10-25T10:00:00Z');
assert.deepEqual(items.map(i=>i.id),['monday','booked','conflict','wait']);
assert.equal(items[0].date,'2026-10-26');assert.equal(items[0].kind,'planned');
assert.equal(items.find(i=>i.id==='conflict').conflict,true);assert.equal(items.find(i=>i.id==='wait').kind,'waiting');
items=run(week,{...profile,paused:true},'2026-10-25T10:00:00Z');
assert.equal(items.find(i=>i.id==='booked').paused,false);assert.equal(items.find(i=>i.id==='wait').paused,true);
const past={week_start:'2026-10-26',events:[],past_bookings:[event('old','Yoga','2026-10-26T10:00:00+03:00',true),event('not-booked','Yoga','2026-10-26T11:00:00+03:00')]};
items=run(past,{wishlist:[wish('Yoga',0)]},'2026-10-30T12:00:00Z');
assert.deepEqual(items.map(i=>i.id),['old']);assert.equal(items[0].past,true);
items=run({week_start:'2026-10-26',events:[]},{waitlist:[{id:'orphan',title:'Boxing',start:'2026-10-28T12:00:00+03:00'}]},'2026-10-25T10:00:00Z');
assert.equal(items[0].missing,true);assert.equal(items[0].kind,'waiting');
items=run(week,{...profile,waitlist:[...profile.waitlist,{...week.events[5]}]},'2026-10-25T10:00:00Z');
assert.equal(items.find(i=>i.id==='cancel').kind,'waiting');
console.log('Weekly plan: timezone, deduplication, matching, pause, conflicts, cancellations, past bookings and waiting list checks passed.');
